#!/usr/bin/env bash
# Sourced from your rc file (the block setup.sh adds). Loads the shared config, then the
# active profile's, then your own config.sh last so anything in it wins.

[[ -n "${ENVSETUP_ROOT:-}" ]] || return 0

# shellcheck source=shell/state.sh
source "$ENVSETUP_ROOT/shell/state.sh"
ENVSETUP_PROFILE="" ENVSETUP_MODE=full
[[ -f "$ENVSETUP_STATE/profile" ]] && ENVSETUP_PROFILE="$(<"$ENVSETUP_STATE/profile")"
[[ "$ENVSETUP_PROFILE" == work && -f "$ENVSETUP_STATE/mode" ]] && ENVSETUP_MODE="$(<"$ENVSETUP_STATE/mode")"

# Every shell, interactive or not (`ssh host cmd`, scp, rsync, scripts): Homebrew on PATH
# (macOS), the exports (EDITOR for `ssh host git commit`; not in work lite), and the
# exports for dotfiles "Move dotfiles to XDG dirs" moved, or the programs would recreate
# them in $HOME. None print anything or run a program, so commands over ssh stay fast
# and scp's silent remote shell stays silent.
# shellcheck source=shell/shared/brew.sh
source "$ENVSETUP_ROOT/shell/shared/brew.sh"
# shellcheck source=shell/shared/exports.sh
[[ "$ENVSETUP_MODE" == lite ]] || source "$ENVSETUP_ROOT/shell/shared/exports.sh"
# shellcheck source=/dev/null # generated by lib/xdg.sh
[[ -f "$ENVSETUP_STATE/xdg.sh" ]] && source "$ENVSETUP_STATE/xdg.sh"

# The rest only for interactive shells: not every distro's ~/.bashrc returns early for
# non-interactive ones (Fedora's doesn't). work lite assumes no sudo, so it only gets the
# prompt, aliases and tool hooks (for tools that happen to be installed).
if [[ $- == *i* ]]; then
	_envsetup_files=(ps1 aliases tools)
	[[ "$ENVSETUP_MODE" == lite ]] || _envsetup_files+=(functions)
	for _envsetup_f in "${_envsetup_files[@]}"; do
		# shellcheck disable=SC1090 # dynamic by design
		source "$ENVSETUP_ROOT/shell/shared/$_envsetup_f.sh"
	done
	if [[ -n "$ENVSETUP_PROFILE" ]]; then
		for _envsetup_f in "$ENVSETUP_ROOT/shell/profiles/$ENVSETUP_PROFILE"/*.sh; do
			# shellcheck disable=SC1090
			[[ -f "$_envsetup_f" ]] && source "$_envsetup_f"
		done
	fi
fi
# config.sh loads in every shell, last so it wins; its interactive-only bits go under
# [[ $- == *i* ]] (see config.example.sh).
# shellcheck source=/dev/null # user-supplied file
[[ -f "$ENVSETUP_STATE/config.sh" ]] && source "$ENVSETUP_STATE/config.sh"

unset _envsetup_files _envsetup_f
